-- database/migrations/V001__tablas_negocio.sql
-- V001: una tabla base por cada uno de los 5 esquemas. Se ejecuta como SYSTEM en FREEPDB1.
-- PROVISIONAL hasta recibir la parte 2 del PDF: estructura minima para verificar el provisionamiento.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

-- Limpieza idempotente (23ai soporta IF EXISTS).
DROP TABLE IF EXISTS ACADEMIA.ALUMNOS;
DROP TABLE IF EXISTS CLINICA.PACIENTES;
DROP TABLE IF EXISTS RETAIL.PRODUCTOS;
DROP TABLE IF EXISTS LOGISTICA.ENVIOS;
DROP TABLE IF EXISTS FINTECH.CUENTAS;

CREATE TABLE ACADEMIA.ALUMNOS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(150) UNIQUE NOT NULL,
  CREADO_EL DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE CLINICA.PACIENTES (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  NUHSA VARCHAR2(20) UNIQUE NOT NULL,
  CREADO_EL DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE RETAIL.PRODUCTOS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  SKU VARCHAR2(40) UNIQUE NOT NULL,
  PRECIO NUMBER(10,2) NOT NULL CHECK (PRECIO >= 0),
  CREADO_EL DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE LOGISTICA.ENVIOS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  CODIGO VARCHAR2(40) UNIQUE NOT NULL,
  DESTINO VARCHAR2(150) NOT NULL,
  CREADO_EL DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE FINTECH.CUENTAS (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  IBAN VARCHAR2(34) UNIQUE NOT NULL,
  SALDO NUMBER(14,2) DEFAULT 0 NOT NULL,
  CREADO_EL DATE DEFAULT SYSDATE NOT NULL
);

EXIT
